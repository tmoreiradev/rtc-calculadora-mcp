def op(sid, data, local, *itens):
    municipio, uf = local
    return {
        "id": sid,
        "operacao": {
            "dhFatoGerador": f"{data}T10:00:00-03:00",
            "municipio": municipio,
            "uf": uf,
            "itens": [dict(it, numero=n) for n, it in enumerate(itens, 1)],
        },
    }


def ncm(codigo, cst, cclass, base, qtd=1, un="UN", aliq=None, **extra):
    it = {"ncm": codigo, "cst": cst, "cClassTrib": cclass, "baseCalculo": base, "quantidade": qtd, "unidade": un}
    if aliq:
        it["aliquotasNominais"] = aliq
    return it | extra


def nbs(codigo, cst, cclass, base, aliq=None):
    it = {"nbs": codigo, "cst": cst, "cClassTrib": cclass, "baseCalculo": base}
    if aliq:
        it["aliquotasNominais"] = aliq
    return it


